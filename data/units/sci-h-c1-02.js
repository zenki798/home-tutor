/* 가상의 원소 A~E 의 선 스펙트럼 (nm). 서로 8 nm 이상 떨어지게 정했다 */
var EL = { A: [420, 530, 655], B: [445, 590], C: [470, 560, 680], D: [500, 615], E: [435, 545, 640] };
function linesOf(names) {
  var all = [];
  names.forEach(function (n) { all = all.concat(EL[n]); });
  return all.sort(function (a, b) { return a - b; });
}
function elementRows(names) {
  return names.map(function (n) { return { label: '원소 ' + n, kind: 'emit', lines: EL[n] }; });
}

