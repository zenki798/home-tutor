    var s = '<svg viewBox="0 0 300 ' + H + '">';
    s += '<text x="70" y="24" font-size="16" text-anchor="middle" fill="currentColor">' + (nx || 'X') + '</text>';
    s += '<text x="230" y="24" font-size="16" text-anchor="middle" fill="currentColor">' + (ny || 'Y') + '</text>';
    s += '<ellipse cx="70" cy="' + cy + '" rx="40" ry="' + (n * gap / 2 + 6) + '" fill="none" stroke="currentColor" stroke-width="1.5"/>';
