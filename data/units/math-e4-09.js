  function dec(v, d) {
    var s = String(Math.abs(v));
    while (s.length <= d) s = '0' + s;
    var out = d === 0 ? s : s.slice(0, s.length - d) + '.' + s.slice(s.length - d);
    return (v < 0 ? '-' : '') + out;
  }
  // 끝의 0 을 지운 글자 (값 그대로)
  function trim(s) {
    if (s.indexOf('.') < 0) return s;
    return s.replace(/0+$/, '').replace(/\.$/, '');
  }

