        title: '소수 한 자리 수의 덧셈과 뺄셈',
        make: function (R) {
          var add = R.bool();
          var a, b, ans;
          do {
            a = R.int(3, 99); b = R.int(2, 99);
            if (!add && b >= a) { var t = a; a = b; b = t; }
            ans = add ? a + b : a - b;
          } while (a % 10 === 0 || b % 10 === 0 || ans % 10 === 0 || ans <= 0 || a === b);
          var as = dec(a, 1), bs = dec(b, 1), ansS = dec(ans, 1);
          var wrong = [];
          var at = a % 10, bt = b % 10, aw = Math.floor(a / 10), bw = Math.floor(b / 10);
          if (add && at + bt >= 10) {
            wrong.push({ a: (aw + bw) + '.' + (at + bt), why: '소수 첫째 자리끼리 더한 ' + (at + bt) + R.josa(at + bt, '을/를') + ' 그대로 썼어요. 0.1이 10개면 1이니 일의 자리로 받아올려요.' });
          }
          if (!add && at < bt) {
            var rev = (aw - bw) * 10 + (bt - at);
            if (rev !== ans && rev > 0) wrong.push({ a: dec(rev, 1), why: '소수 첫째 자리에서 ' + at + '에서 ' + bt + R.josa(bt, '을/를') + ' 뺄 수 없어 거꾸로 뺐어요. 일의 자리에서 1을 받아내려 $' + (at + 10) + '-' + bt + '$' + R.josa(bt, '으로/로') + ' 계산해요.' });
          }
          return {
            type: 'short', check: 'number', concept: 4,
            q: '계산해 보세요.\n\n$' + as + (add ? '+' : '-') + bs + '$',
            answer: ansS,
            wrong: wrong,
            explain: '0.1이 몇 개인지로 생각해요. ' + as + R.josa(a, '은/는') + ' 0.1이 ' + a + '개, ' + bs + R.josa(b, '은/는') + ' 0.1이 ' + b + '개예요.\n\n0.1이 $' + a + (add ? '+' : '-') + b + '=' + ans + '$개이므로 ' + ansS + R.josa(ans, '이에요/예요') + '.',
          };
        },
