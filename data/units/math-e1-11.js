        s += '<circle cx="' + (x + 20) + '" cy="' + (y + 20) + '" r="13" fill="' + (i < a ? 'var(--fig-1)' : 'var(--fig-2)') + '" fill-opacity="0.75" stroke="currentColor" stroke-width="1.5"/>';
