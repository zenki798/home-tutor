        var res = k < 0 ? FLIP[rel] : rel;
        var B = R.F(d - b, k);
        var bv = B.num / B.den;
        function answerFor(r, val, isInt) {
          if (r === 'gt') return Math.floor(val) + 1;
          if (r === 'ge') return isInt ? val : Math.ceil(val);
          if (r === 'lt') return Math.ceil(val) - 1;
          return isInt ? val : Math.floor(val);
        }
        var isInt = B.den === 1;
        var ans = answerFor(res, isInt ? B.num : bv, isInt);
        var askSmall = res === 'gt' || res === 'ge';
