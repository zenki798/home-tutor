  function layerGrids(layers, titles) {
    var C = 26, G = 78, gap = 16, m = 8;
    var n = layers.length;
    var W = m * 2 + n * G + (n - 1) * gap;
    var s = '<svg viewBox="0 0 ' + W + ' 110">';
    for (var i = 0; i < n; i++) {
      var x0 = m + i * (G + gap), y0 = 6;
      for (var c = 1; c <= 9; c++) {
        var r = Math.floor((c - 1) / 3), col = (c - 1) % 3;
        var x = x0 + col * C, y = y0 + r * C;
        var on = layers[i].indexOf(c) >= 0;
        s += '<rect x="' + x + '" y="' + y + '" width="' + C + '" height="' + C + '" fill="' + (on ? 'var(--fig-1)' : 'none') + '" fill-opacity="0.4" stroke="currentColor" stroke-width="1"/>';
        s += '<text x="' + (x + C / 2) + '" y="' + (y + C / 2 + 4) + '" font-size="11" text-anchor="middle" fill="currentColor">' + c + '</text>';
      }
      s += '<text x="' + (x0 + G / 2) + '" y="' + (y0 + G + 18) + '" font-size="10" text-anchor="middle" fill="currentColor">' + titles[i] + '</text>';
    }
    return s + '</svg>';
  }

