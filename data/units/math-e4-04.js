  var SHAPES = [
    { pts: [[0, 0], [1, 0], [1, 2], [2, 2], [2, 3], [0, 3]], w: 2, h: 3 }, // ㄴ 모양
    { pts: [[0, 0], [2, 0], [2, 2], [1, 2], [1, 3], [0, 3]], w: 2, h: 3 }, // 네모 아래에 다리
    { pts: [[0, 0], [0, 3], [2, 3]], w: 2, h: 3 }, // 직각삼각형
    { pts: [[0, 0], [3, 0], [3, 1], [1, 1], [1, 2], [0, 2]], w: 3, h: 2 }, // 팔 길이가 다른 ㄱ 모양
    { pts: [[0, 0], [2, 0], [1, 1], [1, 3], [0, 3]], w: 2, h: 3 }, // 깃발
  ];

  function tf(S, k) {
    var w = S.w, h = S.h, f;
    if (k === 'LR') f = function (p) { return [w - p[0], p[1]]; };
    else if (k === 'UD') f = function (p) { return [p[0], h - p[1]]; };
    else if (k === 'R90') f = function (p) { return [h - p[1], p[0]]; };
    else if (k === 'R180') f = function (p) { return [w - p[0], h - p[1]]; };
    else if (k === 'R270') f = function (p) { return [p[1], w - p[0]]; };
    else if (k === 'T1') f = function (p) { return [p[1], p[0]]; };
    else if (k === 'T2') f = function (p) { return [h - p[1], w - p[0]]; };
    else f = function (p) { return [p[0], p[1]]; };
    var swap = k === 'R90' || k === 'R270' || k === 'T1' || k === 'T2';
    return { pts: S.pts.map(f), w: swap ? h : w, h: swap ? w : h };
  }

  var FALLBACK = ['#2563eb', '#f59e0b', '#10b981', '#ef4444'];
  function grid(ox, oy, cols, rows, c) {
    var d = '', i;
    for (i = 0; i <= cols; i++) d += 'M' + (ox + i * c) + ' ' + oy + 'V' + (oy + rows * c);
    for (i = 0; i <= rows; i++) d += 'M' + ox + ' ' + (oy + i * c) + 'H' + (ox + cols * c);
    return '<path d="' + d + '" fill="none" stroke="currentColor" stroke-opacity="0.28" stroke-width="1"/>';
  }
  function poly(ox, oy, pts, c, ci, dash) {
    return '<polygon points="' + pts.map(function (p) { return (ox + p[0] * c) + ',' + (oy + p[1] * c); }).join(' ') +
      '" fill="var(--fig-' + ci + ', ' + FALLBACK[ci - 1] + ')" fill-opacity="0.4" stroke="currentColor" stroke-width="2" stroke-linejoin="round"' +
      (dash ? ' stroke-dasharray="5 4"' : '') + '/>';
  }
  function txt(x, y, s, size, anchor) {
    return '<text x="' + x + '" y="' + y + '" font-size="' + (size || 15) + '" text-anchor="' + (anchor || 'middle') + '" fill="currentColor">' + s + '</text>';
  }
  // (x1,y1) → (x2,y2) 가로 또는 세로 화살표
  function arrow(x1, y1, x2, y2, dash) {
    var dx = x2 > x1 ? 1 : x2 < x1 ? -1 : 0, dy = y2 > y1 ? 1 : y2 < y1 ? -1 : 0;
    var bx = x2 - dx * 9, by = y2 - dy * 9;
    return '<path d="M' + x1 + ' ' + y1 + 'L' + bx + ' ' + by + '" stroke="currentColor" stroke-width="2"' + (dash ? ' stroke-dasharray="4 3"' : '') + '/>' +
      '<path d="M' + x2 + ' ' + y2 + 'L' + (bx - dy * 5) + ' ' + (by + dx * 5) + 'L' + (bx + dy * 5) + ' ' + (by - dx * 5) + 'Z" fill="currentColor"/>';
  }
  function svgFig(w, h, body, alt) {
    return { type: 'svg', svg: '<svg viewBox="0 0 ' + w + ' ' + h + '">' + body + '</svg>', alt: alt };
  }
  // 도형 여러 개를 5×5 모눈 칸에 하나씩 나란히 (아래에 이름). opt.arrow: 칸 사이에 화살표
  function panels(list, alt, opt) {
    opt = opt || {};
    var c = opt.cell || 16, n = 5, slot = n * c, gap = opt.arrow ? 44 : 14, pad = 8;
    var W = pad * 2 + list.length * slot + (list.length - 1) * gap, H = pad + slot + 28, body = '';
    list.forEach(function (it, i) {
      var ox = pad + i * (slot + gap), oy = pad, S = it.S;
      var dx = Math.floor((n - S.w) / 2), dy = Math.floor((n - S.h) / 2);
      body += grid(ox, oy, n, n, c) + poly(ox + dx * c, oy + dy * c, S.pts, c, it.color || (i === 0 ? 1 : 2)) +
        txt(ox + slot / 2, oy + slot + 21, it.label, 15);
      if (opt.arrow && i < list.length - 1) body += arrow(ox + slot + 8, oy + slot / 2, ox + slot + gap - 8, oy + slot / 2);
    });
    return svgFig(W, H, body, alt);
  }
