  function hom2(a, b, c, lead) {
    var out = '';
    [[a, 'x^{2}'], [b, 'xy'], [c, 'y^{2}']].forEach(function (t) {
      var k = t[0];
      if (!k) return;
      var sign = k < 0 ? '-' : (out || lead ? '+' : '');
      var m = Math.abs(k);
      out += sign + (m === 1 ? '' : m) + t[1];
    });
    return out || '0';
  }
