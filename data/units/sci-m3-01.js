/* 'N2 + 3H2 -> 2NH3' → $\mathrm{N}_{2}+3\mathrm{H}_{2}\rightarrow 2\mathrm{N}\mathrm{H}_{3}$ */
function EQ(s) {
  return '$' + s.split(' -> ').map(function (side) { return side.split(' + ').map(tf).join('+'); }).join('\\rightarrow ') + '$';
}
/* 화학식 하나(계수 없이)의 원자 수 → { n: {원소: 개수}, order: [원소…] } */
function atoms(f) {
  var n = {}, order = [];
  function add(el, k) { if (!(el in n)) { n[el] = 0; order.push(el); } n[el] += k; }
  var re = /([A-Z][a-z]?)(\d*)|\(([^()]*)\)(\d*)/g, m;
  while ((m = re.exec(f))) {
    if (m[1]) add(m[1], m[2] ? Number(m[2]) : 1);
    else {
      var inner = atoms(m[3]);
      var k = m[4] ? Number(m[4]) : 1;
      inner.order.forEach(function (e) { add(e, inner.n[e] * k); });
    }
  }
  return { n: n, order: order };
}
