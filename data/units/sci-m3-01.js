/* 화학식 글자 → TeX. 'H2O' → \mathrm{H}_{2}\mathrm{O}, '2H2O' → 2\mathrm{H}_{2}\mathrm{O} (앞의 수는 계수) */
function tf(s) {
  var m = /^(\d*)(.*)$/.exec(s);
  return m[1] + m[2].replace(/([A-Z][a-z]?)|(\d+)|([()])/g, function (all, el, num, par) {
    if (el) return '\\mathrm{' + el + '}';
    if (num) return '_{' + num + '}';
    return par;
  });
}
