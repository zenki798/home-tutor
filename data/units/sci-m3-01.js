/* 한 쪽(반응물 또는 생성물)의 원소별 원자 수 */
function sideCount(side) {
  var n = {}, order = [];
  side.forEach(function (sp) {
    var a = atoms(sp[1]);
    a.order.forEach(function (e) {
      if (!(e in n)) { n[e] = 0; order.push(e); }
      n[e] += sp[0] * a.n[e];
    });
  });
  return { n: n, order: order };
}
/* 계수 하나를 □로 가린 반응식 TeX */
function rxTex(rx, hide) {
  var k = 0;
  function sp(s) {
    var t = (k === hide ? '\\square ' : (s[0] === 1 ? '' : String(s[0]))) + tf(s[1]);
    k++;
    return t;
  }
  var left = rx.r.map(sp).join('+');
  var right = rx.p.map(sp).join('+');
  return '$' + left + '\\rightarrow ' + right + '$';
}

