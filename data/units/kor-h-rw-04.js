    var pick = R.choices(a, d.map(function (x) { return x[0]; }), d.length + 1);
    return {
      choices: pick.choices,
      answer: pick.answer,
      why: pick.choices.map(function (c) {
        if (c === a) return '';
        for (var i = 0; i < d.length; i++) if (d[i][0] === c) return d[i][1];
        return '';
      }),
    };
