  function tf(s) {
    var charge = '';
    var c = /(\^\d+[+-]|[+-])$/.exec(s);
    if (c) { charge = '^{' + c[1].replace('^', '') + '}'; s = s.slice(0, c.index); }
    var m = /^(\d*)(.*)$/.exec(s);
    return m[1] + m[2].replace(/([A-Z][a-z]?)|(\d+)|([()])/g, function (all, el, num, par) {
      if (el) return '\\mathrm{' + el + '}';
      if (num) return '_{' + num + '}';
      return par;
    }) + charge;
  }
