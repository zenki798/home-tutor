/* 화학식 글자 → TeX. 'H2O' → \mathrm{H}_{2}\mathrm{O} (앞의 수는 계수) */
function tf(s) {
  var m = /^(\d*)(.*)$/.exec(s);
  return m[1] + m[2].replace(/([A-Z][a-z]?)|(\d+)/g, function (all, el, num) {
    if (el) return '\\mathrm{' + el + '}';
    return '_{' + num + '}';
  });
}
function F(s) { return '$' + tf(s) + '$'; }
/* 이온 TeX: ion('Mg', 2) → \mathrm{Mg}^{2+}, ion('Cl', -1) → \mathrm{Cl}^{-} */
function ion(sym, z) {
  var a = Math.abs(z);
  return tf(sym) + '^{' + (a === 1 ? '' : a) + (z > 0 ? '+' : '-') + '}';
}
function I(sym, z) { return '$' + ion(sym, z) + '$'; }
function gcd(a, b) { return b ? gcd(b, a % b) : a; }

