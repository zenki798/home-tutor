/* 분자량(화학식량) 생성기에 쓰는 물질: [화학식, 이름, 이온 결합 물질이면 1] */
var CMP = [
  ['H2O', '물', 0], ['CO2', '이산화 탄소', 0], ['NH3', '암모니아', 0], ['CH4', '메테인', 0],
  ['O2', '산소', 0], ['N2', '질소', 0], ['C6H12O6', '포도당', 0], ['HCl', '염화 수소', 0],
  ['H2SO4', '황산', 0], ['C2H6', '에테인', 0], ['C3H8', '프로페인', 0], ['C2H5OH', '에탄올', 0],
  ['SO2', '이산화 황', 0], ['NO2', '이산화 질소', 0], ['HNO3', '질산', 0], ['CH3COOH', '아세트산', 0],
  ['H2S', '황화 수소', 0], ['SO3', '삼산화 황', 0],
  ['NaCl', '염화 나트륨', 1], ['MgCl2', '염화 마그네슘', 1], ['CaCl2', '염화 칼슘', 1], ['CaCO3', '탄산 칼슘', 1],
  ['NaOH', '수산화 나트륨', 1], ['MgO', '산화 마그네슘', 1], ['CaO', '산화 칼슘', 1], ['Na2CO3', '탄산 나트륨', 1],
  ['NaHCO3', '탄산수소 나트륨', 1],
];
function molarMass(f) {
  return parts(f).reduce(function (s, p) { return s + AM[p[0]] * p[1]; }, 0);
}
/* 정수 d × 10^e 를 과학적 표기 TeX 로: sciTex(45150, 19) → '4.515\times10^{23}' */
function sciTex(d, e) {
  var s = String(d);
  while (s.length > 1 && s.charAt(s.length - 1) === '0') { s = s.slice(0, -1); e += 1; }
  var mant = s.length > 1 ? s.charAt(0) + '.' + s.slice(1) : s;
  return mant + '\\times10^{' + (e + s.length - 1) + '}';
}
function nInt(nS) { return Math.round(parseFloat(nS) * 100); } // 몰수 × 100 (정수로 계산)

