  function say(counts) {
    var names = counts.length === 3 ? ['큰 그림', '중간 그림', '작은 그림'] : ['큰 그림', '작은 그림'];
    var parts = [];
    counts.forEach(function (c, k) { if (c > 0) parts.push(names[k] + ' ' + c + '개'); });
    return parts.join(', ');
  }

