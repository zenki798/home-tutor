  function fact(n) { var f = 1; for (var i = 2; i <= n; i++) f *= i; return f; }
  function perm(n, r) { if (r > n) return 0; var f = 1; for (var i = 0; i < r; i++) f *= n - i; return f; }
  function C(n, r) { return r < 0 || r > n ? 0 : perm(n, r) / fact(r); }
  function H(n, r) { return r < 0 ? 0 : C(n + r - 1, r); }
  function Ht(n, r) { return '{}_{' + n + '}\\mathrm{H}_{' + r + '}'; }
  function Ct(n, r) { return '{}_{' + n + '}\\mathrm{C}_{' + r + '}'; }
  /* ₙHᵣ = ₙ₊ᵣ₋₁Cᵣ = 값 (C 는 작은 쪽으로 계산한 것도 함께) */
  function Hchain(n, r) {
    var N = n + r - 1, s = Ht(n, r) + '=' + Ct(N, r);
    if (N - r < r) s += '=' + Ct(N, N - r);
    return s + '=' + H(n, r);
  }
