/* 화학식 글자 → TeX. 'CO2' → \mathrm{C}\mathrm{O}_{2} */
function tf(s) {
  var m = /^(\d*)(.*)$/.exec(s);
  return m[1] + m[2].replace(/([A-Z][a-z]?)|(\^\d*[+-])|(\d+)|([()])/g, function (all, el, chg, num, par) {
    if (el) return '\\mathrm{' + el + '}';
    if (chg) return '^{' + chg.slice(1) + '}';
    if (num) return '_{' + num + '}';
    return par;
  });
}
function F(s) { return '$' + tf(s) + '$'; }
/* 주어진 측정값을 유효 숫자 3자리로 보이기 (값이 바뀌면 그대로 둔다): 0.5 → '0.500', 2 → '2.00' */
function disp(x) {
  var s = Number(x).toPrecision(3);
  return (Number(s) === Number(x) && s.indexOf('e') < 0) ? s : String(x);
}
function isDec(x, places) { var k = x * Math.pow(10, places); return Math.abs(k - Math.round(k)) < 1e-7; }
function cel(T) { return String(T - 273).replace('-', '−') + ' °C'; }

