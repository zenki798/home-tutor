  function plain(R, coefs) {
    var n = coefs.length - 1, s = '';
    for (var i = 0; i <= n; i++) {
      var k = n - i;
      var c = typeof coefs[i] === 'number' ? R.F(coefs[i], 1) : coefs[i];
      if (c.isZero()) continue;
      var a = c.abs();
      var mag = a.isInt() ? String(a.num) : '(' + a.num + '/' + a.den + ')';
      if (k > 0 && a.isInt() && a.num === 1) mag = '';
      s += (c.sign() < 0 ? '-' : (s ? '+' : '')) + mag + (k === 0 ? '' : k === 1 ? 'x' : 'x^' + k);
    }
    return s || '0';
  }
  // 한 항 c·x^k 의 TeX
  function mono(R, c, k) {
    var a = [c];
    for (var i = 0; i < k; i++) a.push(0);
    return R.fmt.poly(a);
  }
  // 정수 계수 다항식의 값
  function val(coefs, x) {
    var s = 0;
    for (var i = 0; i < coefs.length; i++) s = s * x + coefs[i];
    return s;
  }

