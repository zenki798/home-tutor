  function chainFig(cols, links) {
    var n = 0;
    cols.forEach(function (c) { n = Math.max(n, c[1].length); });
    var gap = 34, top = 40, H = top + n * gap + 16, cy = top + n * gap / 2, step = 150;
    var W = step * (cols.length - 1) + 120;
    function cx(k) { return 60 + step * k; }
    function yAt(k, i) { return top + (n - cols[k][1].length) * gap / 2 + gap * i + gap / 2; }
    var s = '<svg viewBox="0 0 ' + W + ' ' + H + '">';
    cols.forEach(function (c, k) {
      s += '<text x="' + cx(k) + '" y="24" font-size="16" text-anchor="middle" fill="currentColor">' + c[0] + '</text>';
      s += '<ellipse cx="' + cx(k) + '" cy="' + cy + '" rx="38" ry="' + (n * gap / 2 + 6) + '" fill="none" stroke="currentColor" stroke-width="1.5"/>';
      c[1].forEach(function (t, i) {
        s += '<text x="' + cx(k) + '" y="' + (yAt(k, i) + 5) + '" font-size="15" text-anchor="middle" fill="currentColor">' + t + '</text>';
      });
    });
    links.forEach(function (l) {
      var k = l[0], x1 = cx(k) + 16, y1 = yAt(k, l[1]), x2 = cx(k + 1) - 16, y2 = yAt(k + 1, l[2]);
      var dx = x2 - x1, dy = y2 - y1, L = Math.sqrt(dx * dx + dy * dy), ux = dx / L, uy = dy / L;
      var bx = x2 - ux * 9, by = y2 - uy * 9, color = k % 2 ? 'var(--fig-2)' : 'var(--fig-1)';
      s += '<line x1="' + x1 + '" y1="' + y1 + '" x2="' + bx.toFixed(1) + '" y2="' + by.toFixed(1) + '" stroke="' + color + '" stroke-width="1.8"/>';
      s += '<polygon points="' + x2 + ',' + y2 + ' ' + (bx - uy * 4.5).toFixed(1) + ',' + (by + ux * 4.5).toFixed(1) + ' ' + (bx + uy * 4.5).toFixed(1) + ',' + (by - ux * 4.5).toFixed(1) + '" fill="' + color + '"/>';
    });
    return s + '</svg>';
  }

