  function dec4(v) {
    var s = v < 0 ? '-' : '', a = Math.abs(v);
    var ip = Math.floor(a / 10000), fp = String(a % 10000);
    while (fp.length < 4) fp = '0' + fp;
    return s + ip + '.' + fp;
  }
