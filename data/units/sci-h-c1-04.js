        var xn = ELS[X][0], cn = ELS[C][0];
        function desc(Z) { return group(Z) === 18 ? '비활성 기체' : '원자가 전자가 ' + valence(Z) + '개인 원소'; }
        var samePeriod = [], others = [];
        for (var z = 1; z <= 20; z++) {
          if (z === X || grp.indexOf(z) >= 0) continue;
          // 수소는 1족이라 알칼리 금속 문제의 오답으로 넣으면 "같은 족" 기준으로 정답이 둘이 된다
          if (z === 1 && grp[0] === 3) continue;
          if (period(z) === period(X)) samePeriod.push(z); else others.push(z);
        }
        // 같은 주기 원소 2개 + 다른 주기 원소 1개를 먼저 (주기만 보고 정답을 고를 수 없게)
