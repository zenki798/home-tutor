  // N 을 10^p 로 나눈 소수 글자 (끝의 0 은 지운다). 예: dec(206, 2) → '2.06', dec(120, 2) → '1.2'
  function dec(N, p) {
    if (p <= 0) return String(N * Math.pow(10, -p));
    var s = String(N);
    while (s.length < p + 1) s = '0' + s;
    var i = s.slice(0, s.length - p), f = s.slice(s.length - p).replace(/0+$/, '');
    return f ? i + '.' + f : i;
  }
  // 소수 글자의 소수점 아래 자리 수
  function places(s) { var k = s.indexOf('.'); return k < 0 ? 0 : s.length - k - 1; }

