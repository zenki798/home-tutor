  function jt(R, tex, pair) {
    var t = String(tex).trim();
    if (/\^\{[^{}]*\}$/.test(t)) return R.josa('곱', pair);
    return R.josa(t, pair);
  }
  function paren(n) { return n < 0 ? '(' + n + ')' : String(n); }
  // 내림차순 계수 cs 를 x=a 에 넣는 식 (TeX): 2\cdot(-1)^{3}+3\cdot(-1)^{2}-(-1)+4
  function subst(cs, a) {
    var n = cs.length - 1, out = '';
    for (var i = 0; i <= n; i++) {
      var c = cs[i], k = n - i;
      if (!c) continue;
      var sign = c < 0 ? '-' : (out ? '+' : '');
      var m = Math.abs(c);
      var pw = k === 0 ? '' : (k === 1 ? paren(a) : paren(a) + '^{' + k + '}');
      var body = k === 0 ? String(m) : (m === 1 ? pw : m + '\\cdot ' + pw);
      out += sign + body;
    }
    return out || '0';
  }
  function evalPoly(cs, a) { var v = 0; for (var i = 0; i < cs.length; i++) v = v * a + cs[i]; return v; }
  // 조립제법: cs 를 x-a 로 나눈 몫 계수와 나머지, 곱한 값들
  function synth(cs, a) {
    var b = [cs[0]], prods = [];
    for (var i = 1; i < cs.length; i++) { var p = b[i - 1] * a; prods.push(p); b.push(cs[i] + p); }
    return { q: b.slice(0, -1), r: b[b.length - 1], prods: prods };
  }
  function uniqByKey(correctKey, cands) {
    var seen = [String(correctKey)], out = [];
    cands.forEach(function (c) {
      var k = String(c[1]);
      if (seen.indexOf(k) >= 0) return;
      seen.push(k); out.push(c);
    });
    return out;
  }

