  function readKor(n) {
    var units = ['', '만', '억', '조'];
    var parts = [];
    var i = 0;
    while (n > 0 && i < units.length) {
      var g = n % 10000;
      if (g) parts.unshift(g + units[i]);
      n = Math.floor(n / 10000);
      i++;
    }
    return parts.join(' ');
  }
  // 오른쪽에서부터 네 자리씩 끊은 모양: 3024500000 → '30 / 2450 / 0000'
  function groups(n) {
    var s = String(n), out = [];
    while (s.length > 4) { out.unshift(s.slice(-4)); s = s.slice(0, -4); }
    out.unshift(s);
    return out.join(' / ');
  }
