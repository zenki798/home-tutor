        var askNatural = R.bool();
        var right = askNatural ? NATURAL : HUMAN;
        var other = askNatural ? HUMAN : NATURAL;
        var correct = R.pick(right);
        var picked = R.choices(correct, R.sample(other, 5), 4);
        var kind = askNatural ? '자연환경' : '인문환경';
        var otherKind = askNatural ? '인문환경' : '자연환경';
        return {
          type: 'choice', concept: 0,
          q: '다음 가운데 **' + kind + '**은 무엇일까요?',
          choices: picked.choices,
          answer: picked.answer,
          why: picked.choices.map(function (c) {
            if (c === correct) return '';
            return c + R.josa(c, '은/는') + (askNatural ? ' 사람이 만든 ' : ' 사람이 만들지 않은 ') + otherKind + '이에요.';
          }),
          explain: correct + R.josa(correct, '은/는') + (askNatural ? ' 사람이 만들지 않은 자연 그대로의 환경이라 자연환경이에요.' : ' 사람이 자연환경을 이용하여 만든 것이라 인문환경이에요.'),
        };
