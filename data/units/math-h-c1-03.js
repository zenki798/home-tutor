    var pick = R.choices('$' + correct[0] + '$', R.shuffle(list).map(function (c) { return '$' + c[0] + '$'; }));
    return {
      choices: pick.choices,
      answer: pick.answer,
      why: pick.choices.map(function (ch, i) { return i === pick.answer ? '' : reason[ch] || ''; }),
    };
