  function distinctByValue(correctCoef, cands) {
    var seen = [String(correctCoef)], out = [];
    cands.forEach(function (c) {
      var key = String(c[1]);
      if (seen.indexOf(key) >= 0) return;
      seen.push(key); out.push(c);
    });
    return out;
  }
