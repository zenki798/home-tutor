  function jt(R, tex, pair) {
    var t = String(tex).trim();
    if (/\^\{[^{}]*\}$/.test(t)) return R.josa('곱', pair);
    return R.josa(t, pair);
  }
  // 내림차순 계수 다항식의 곱
  function mul(a, b) {
    var out = [];
    for (var i = 0; i < a.length + b.length - 1; i++) out.push(0);
    for (var j = 0; j < a.length; j++) for (var k = 0; k < b.length; k++) out[j + k] += a[j] * b[k];
    return out;
  }
  function mulAll(list) { return list.reduce(function (acc, f) { return mul(acc, f); }, [1]); }
  function isSquare(n) { if (n < 0) return false; var r = Math.round(Math.sqrt(n)); return r * r === n; }
  function synth(cs, a) {
    var b = [cs[0]], prods = [];
    for (var i = 1; i < cs.length; i++) { var p = b[i - 1] * a; prods.push(p); b.push(cs[i] + p); }
    return { q: b.slice(0, -1), r: b[b.length - 1], prods: prods };
  }
