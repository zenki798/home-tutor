  function BM(rows) {
    return '\\begin{bmatrix} ' + rows.map(function (r) { return r.join(' & '); }).join(' \\\\ ') + ' \\end{bmatrix}';
  }
  // 첨가행렬: 각 행의 마지막 칸이 상수항 (세로줄은 \mid 칸으로 그린다)
  function AUG(rows) {
    return '\\begin{bmatrix} ' + rows.map(function (r) {
      return r.slice(0, -1).join(' & ') + ' & \\mid & ' + r[r.length - 1];
    }).join(' \\\\ ') + ' \\end{bmatrix}';
  }
  // 일차식의 왼쪽 변: 계수(수 또는 'a' 같은 글자)와 변수
  function lhs(coefs, vars) {
    var s = '';
    for (var i = 0; i < coefs.length; i++) {
      var c = coefs[i], v = vars[i];
      if (typeof c === 'string') { s += (s ? '+' : '') + c + v; continue; }
      if (c === 0) continue;
      var abs = Math.abs(c);
      s += (c < 0 ? '-' : (s ? '+' : '')) + (abs === 1 ? '' : abs) + v;
    }
    return s || '0';
  }
  // 연립방정식: rows 의 마지막 칸이 우변
  function sys(rows, vars) {
    vars = vars || ['x', 'y', 'z'];
    return '\\begin{cases} ' + rows.map(function (r) {
      return lhs(r.slice(0, -1), vars) + '=' + r[r.length - 1];
    }).join(' \\\\ ') + ' \\end{cases}';
  }
