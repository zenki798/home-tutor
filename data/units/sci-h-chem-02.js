/* 화학식 글자 → TeX. 'H2O' → \mathrm{H}_{2}\mathrm{O}, '2H2O' → 2\mathrm{H}_{2}\mathrm{O} (앞의 수는 계수) */
function tf(s) {
  var m = /^(\d*)(.*)$/.exec(s);
  return m[1] + m[2].replace(/([A-Z][a-z]?)|(\d+)|([()])/g, function (all, el, num, par) {
    if (el) return '\\mathrm{' + el + '}';
    if (num) return '_{' + num + '}';
    return par;
  });
}
function F(s) { return '$' + tf(s) + '$'; }
/* 반응식 TeX: [[계수, 화학식], …] 두 개 → 'aA+bB\rightarrow cC' (계수 1 은 생략) */
function side(arr) {
  return arr.map(function (x) { return (x[0] === 1 ? '' : x[0]) + tf(x[1]); }).join('+');
}
function eq(L, P) { return side(L) + '\\rightarrow ' + side(P); }
function E(L, P) { return '$' + eq(L, P) + '$'; }

