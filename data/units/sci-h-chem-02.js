var AM = { H: 1, C: 12, N: 14, O: 16, Na: 23, Mg: 24, Al: 27, S: 32, Cl: 35.5, Ca: 40, Fe: 56, Zn: 65 };
function parts(f) {
  var out = [], re = /([A-Z][a-z]?)(\d*)/g, m;
  while ((m = re.exec(f))) {
    var k = m[2] ? Number(m[2]) : 1, found = false;
    for (var i = 0; i < out.length; i++) if (out[i][0] === m[1]) { out[i][1] += k; found = true; }
    if (!found) out.push([m[1], k]);
  }
  return out;
}
function molarMass(f) { return parts(f).reduce(function (s, p) { return s + AM[p[0]] * p[1]; }, 0); }

