function coefOf(r, f) {
  var all = r.L.concat(r.P);
  for (var i = 0; i < all.length; i++) if (all[i][1] === f) return all[i][0];
  return 0;
}
function amNote(fs) {
  var seen = {}, list = [];
  fs.forEach(function (f) { parts(f).forEach(function (p) { if (!seen[p[0]]) { seen[p[0]] = true; list.push(p[0]); } }); });
  return '(원자량: ' + list.map(function (e) { return e + ' ' + AM[e]; }).join(', ') + ')';
}
