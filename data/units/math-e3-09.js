    body += Dot(ax, cy) + Dot(bx, cy) + Dot(top[0], top[1]);
    body += T(ax - 4, cy + 18, 'ㄱ') + T(bx + 4, cy + 18, 'ㄴ') + T(top[0], top[1] - 9, 'ㄷ');
