  function frac(n, d) {
    var a = n, b = d;
    while (b) { var t = a % b; a = b; b = t; }
    n /= a; d /= a;
    var dd = d;
    while (dd % 2 === 0) dd /= 2;
    while (dd % 5 === 0) dd /= 5;
    return {
      n: n, d: d,
      s: d === 1 ? String(n) : n + '/' + d,
      tex: d === 1 ? String(n) : '\\dfrac{' + n + '}{' + d + '}',
      dec: dd === 1 ? String(Math.round(n / d * 10000) / 10000) : null,
    };
  }

