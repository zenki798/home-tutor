    function label(x, y, t) { return '<text x="' + x + '" y="' + y + '" font-size="15" font-weight="bold" text-anchor="middle" dominant-baseline="central" fill="currentColor">' + t + '</text>'; }
    s += dot(X(0), Y(0)) + label(X(0) - 13, Y(0) + 13, 'A');
    s += dot(X(a), Y(b)) + label(X(a) + 13, Y(b) - 13, 'B');
    var alt = '가로 ' + a + '칸, 세로 ' + b + '칸인 바둑판 모양의 길. 왼쪽 아래 꼭짓점이 A, 오른쪽 위 꼭짓점이 B';
