  function fact(n) { var f = 1; for (var i = 2; i <= n; i++) f *= i; return f; }
  function perm(n, r) { if (r > n) return 0; var f = 1; for (var i = 0; i < r; i++) f *= n - i; return f; }
  function C(n, r) { return r < 0 || r > n ? 0 : perm(n, r) / fact(r); }
  function Pi(n, r) { return '{}_{' + n + '}\\Pi_{' + r + '}'; }
  function wrongs(ans, list) {
    var seen = [Number(ans)], out = [];
    list.forEach(function (w) {
      var v = Number(w[0]);
      if (!isFinite(v) || v <= 0 || seen.indexOf(v) >= 0) return;
      seen.push(v);
      out.push({ a: String(w[0]), why: w[1] });
    });
    return out;
  }

