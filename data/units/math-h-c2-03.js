  function par(n) { return n < 0 ? '(' + n + ')' : String(n); }
  // n = k^2 * m
  function rad(n) {
    var k = 1, m = n, f = 2;
    while (f * f <= m) {
      while (m % (f * f) === 0) { m /= f * f; k *= f; }
      f++;
    }
    return { k: k, m: m };
  }
  function radTex(n) {
    var r = rad(n);
    if (r.m === 1) return String(r.k);
    return (r.k === 1 ? '' : r.k) + '\\sqrt{' + r.m + '}';
  }
  // (x-a)^2 꼴 TeX: a=0 이면 x^2
  function sqTex(v, a) {
    if (a === 0) return v + '^2';
    return '(' + v + (a > 0 ? '-' + a : '+' + (-a)) + ')^2';
  }
  // 원의 표준형 TeX
