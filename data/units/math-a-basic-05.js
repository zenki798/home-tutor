  // 정수 n 을 10^p 로 나눈 소수 글자 (끝의 0 은 지운다). dec(375, 3) → '0.375', dec(120, 2) → '1.2'
  function dec(n, p) {
    var neg = n < 0;
    var s = String(Math.abs(n));
    if (p <= 0) return (neg ? '-' : '') + s + (p < 0 ? new Array(-p + 1).join('0') : '');
    while (s.length <= p) s = '0' + s;
    var r = s.slice(0, s.length - p) + '.' + s.slice(s.length - p);
    r = r.replace(/0+$/, '').replace(/\.$/, '');
    return (neg ? '-' : '') + r;
  }
  // 끝의 0 을 지우지 않은 소수 글자. raw(120, 3) → '0.120'
  function raw(n, p) {
    var s = String(Math.abs(n));
    if (p <= 0) return s;
    while (s.length <= p) s = '0' + s;
    return s.slice(0, s.length - p) + '.' + s.slice(s.length - p);
  }
  function gcd(a, b) { a = Math.abs(a); b = Math.abs(b); while (b) { var t = a % b; a = b; b = t; } return a; }
  // 소수 글자 → 분수 (R.F). '0.375' → 3/8
  function fracOf(R, s) {
    var parts = String(s).split('.');
    var places = parts[1] ? parts[1].length : 0;
    return R.F(Number(parts[0] + (parts[1] || '')), Math.pow(10, places));
  }
  // 10 의 배수가 아닌 정수 (소수 끝자리가 0 이 되지 않게)
  function noZeroEnd(R, a, b) {
    var v;
    do { v = R.int(a, b); } while (v % 10 === 0);
    return v;
  }

