      if (i > 0) s += '<line x1="' + L + '" y1="' + yy + '" x2="' + RX + '" y2="' + yy + '" stroke="currentColor" stroke-opacity="0.2"/>';
      s += '<text x="' + (L - 7) + '" y="' + r1(yy + 4) + '" text-anchor="end" fill="currentColor">' + v + '</text>';
