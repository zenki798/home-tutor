  var SINO = ['영', '일', '이', '삼', '사', '오', '육', '칠', '팔', '구'];
  var GROUP = ['', '만', '억', '조'];
  var PLACE = ['일', '십', '백', '천', '만', '십만', '백만', '천만', '억', '십억', '백억', '천억', '조'];

  // 네 자리 이하의 수를 읽는 말: 6527 → 육천오백이십칠, 1011 → 천십일
  function read4(n) {
    var s = '', u = ['천', '백', '십', ''], d = [Math.floor(n / 1000), Math.floor(n / 100) % 10, Math.floor(n / 10) % 10, n % 10];
    for (var i = 0; i < 4; i++) {
      if (!d[i]) continue;
      s += (d[i] === 1 && i < 3 ? '' : SINO[d[i]]) + u[i];
    }
    return s;
  }
  // 큰 수를 네 자리씩 끊어 읽는 말: 36527 → 삼만 육천오백이십칠, 10000 → 만, 100000000 → 일억
  function readBig(n) {
    var parts = [], g = 0;
    while (n > 0) {
      var v = n % 10000;
      n = Math.floor(n / 10000);
      if (v) parts.unshift((g === 1 && v === 1 && n === 0 ? '' : read4(v)) + GROUP[g]);
      g++;
    }
    return parts.join(' ');
  }
  function pow10(k) { var p = 1; for (var i = 0; i < k; i++) p *= 10; return p; }
  // 일의 자리부터 네 자리씩 끊어 보이기: 348205600 → 3|4820|5600
  function groupCut(n) {
    var s = String(n), out = [];
    while (s.length > 4) { out.unshift(s.slice(-4)); s = s.slice(0, -4); }
    out.unshift(s);
    return out.join('|');
  }
  // 묶음을 네 자리로 채우지 않고 쓰는 실수: 207000000(2|0700|0000) → 27000000
  function lazyWrite(n) {
    return groupCut(n).split('|').map(function (g, i) {
      if (i === 0 || /^0+$/.test(g)) return g;
      return g.replace(/^0+/, '');
    }).join('');
  }
  function range(a, b) { var r = []; for (var i = a; i <= b; i++) r.push(i); return r; }

