  function caseProblem(R, lead, bank, names, why, concept) {
    var c = R.pick(bank);
    var excl = c[3] || [];
    var wrongs = names.filter(function (n) { return n !== c[1] && excl.indexOf(n) < 0; });
    var ch = R.choices(c[1], wrongs, wrongs.length + 1);
    return {
      type: 'choice',
      q: lead + '\n\n' + c[0],
      choices: ch.choices,
      answer: ch.answer,
      why: ch.choices.map(function (n) { return n === c[1] ? '' : why[n]; }),
      explain: c[2],
      concept: typeof concept === 'number' ? concept : concept[c[1]],
    };
  }

