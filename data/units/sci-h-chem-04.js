function en(x) { return (EN[x] / 10).toFixed(1); }
function bond(a, b) { return a + '–' + b; }
function enNote(list) {
  var seen = {}, out = [];
  list.forEach(function (x) { if (!seen[x]) { seen[x] = true; out.push(x + ' ' + en(x)); } });
  return '(전기 음성도: ' + out.join(', ') + ')';
}
function d(t) { return '$\\delta' + (t > 0 ? '+' : '-') + '$'; }
