  function secClock(h, m, s) {
    var cx = 120, cy = 120, r = 108, o = [];
    function xy(len, deg) {
      var a = deg * Math.PI / 180;
      return [Math.round((cx + len * Math.sin(a)) * 10) / 10, Math.round((cy - len * Math.cos(a)) * 10) / 10];
    }
    function seg(r1, r2, deg) {
      var p = xy(r1, deg), q = xy(r2, deg);
      return 'M' + p[0] + ' ' + p[1] + 'L' + q[0] + ' ' + q[1];
    }
    o.push('<circle cx="120" cy="120" r="108" fill="currentColor" fill-opacity="0.04" stroke="currentColor" stroke-width="3"/>');
    var minor = '', major = '';
    for (var i = 0; i < 60; i++) {
      if (i % 5 === 0) major += seg(r - 5, r - 15, i * 6);
      else minor += seg(r - 5, r - 10, i * 6);
    }
    o.push('<path d="' + minor + '" fill="none" stroke="currentColor" stroke-width="1.3"/>');
    o.push('<path d="' + major + '" fill="none" stroke="currentColor" stroke-width="3" stroke-linecap="round"/>');
    for (var k = 1; k <= 12; k++) {
      var t = xy(r - 31, k * 30);
      o.push('<text x="' + t[0] + '" y="' + t[1] + '" font-size="20" text-anchor="middle" dominant-baseline="central" fill="currentColor">' + k + '</text>');
    }
    function hand(deg, len, back, w, style) {
      var p = xy(-back, deg), q = xy(len, deg);
      return '<line x1="' + p[0] + '" y1="' + p[1] + '" x2="' + q[0] + '" y2="' + q[1] + '" stroke-width="' + w + '" stroke-linecap="round" style="stroke:' + style + '"/>';
    }
    o.push(hand(((h % 12) + m / 60 + s / 3600) * 30, 54, 10, 7, 'currentColor'));
    o.push(hand((m + s / 60) * 6, 86, 14, 3.5, 'var(--fig-1)'));
    o.push(hand(s * 6, 96, 18, 1.5, 'var(--fig-2)'));
    o.push('<circle cx="120" cy="120" r="5.5" fill="currentColor"/>');
    return {
      type: 'svg',
      alt: '시침, 분침, 초바늘이 있는 시계',
      svg: '<svg viewBox="0 0 240 240">' + o.join('') + '</svg>',
    };
  }

