            if (v === 8) wrongs.push({ a: '8', why: 'DNA는 S기에 한 번만 복제되므로 G₁기(2)의 두 배인 4를 넘지 않습니다.' });
            else if (v === 4) wrongs.push({ a: '4', why: '복제 직후(G₂기~감수 1분열)의 값입니다. 이 단계에 오기까지 세포가 나뉘었는지 확인해 보십시오.' });
