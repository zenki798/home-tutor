  // 100칸 모눈 가운데 n칸 색칠
  function grid100(n, alt) {
    var s = 18, x0 = 10, y0 = 10, out = '';
    for (var i = 0; i < 100; i++) {
      var r = Math.floor(i / 10), c = i % 10;
      out += '<rect x="' + (x0 + c * s) + '" y="' + (y0 + r * s) + '" width="' + s + '" height="' + s + '" fill="' +
        (i < n ? 'var(--fig-1)' : 'none') + '"' + (i < n ? ' fill-opacity="0.45"' : '') + ' stroke="currentColor" stroke-width="1"/>';
    }
    out += '<rect x="' + x0 + '" y="' + y0 + '" width="' + (10 * s) + '" height="' + (10 * s) + '" fill="none" stroke="currentColor" stroke-width="2"/>';
    return { type: 'svg', svg: '<svg viewBox="0 0 200 200">' + out + '</svg>', alt: alt };
  }
  // 비의 여러 가지 읽기 (a 가 비교하는 양, b 가 기준량)
