  var KITE = [[100, 18], [160, 75], [100, 150], [40, 75]];
  // 평행사변형 ㄱㄴㄷㄹ 과 대칭의 중심 ㅇ
  var PARA = [[65, 30], [195, 30], [155, 120], [25, 120]];
