  function wrongs(ans, list) {
    var seen = [Number(ans)], out = [];
    list.forEach(function (w) {
      var v = Number(w[0]);
      if (!isFinite(v) || seen.some(function (s) { return Math.abs(s - v) < 1e-9; })) return;
      seen.push(v);
      out.push({ a: String(w[0]), why: w[1] });
    });
    return out;
  }
  function med(a) { var n = a.length, h = Math.floor(n / 2); return n % 2 ? a[h] : (a[h - 1] + a[h]) / 2; }
  // 크기순 자료(개수 짝수) → { q1, q2, q3, lower, upper }
  function quart(s) { var h = s.length / 2, lo = s.slice(0, h), up = s.slice(h); return { q1: med(lo), q2: med(s), q3: med(up), lower: lo, upper: up }; }
  // 중앙값 구하는 식 (TeX): 가운데 두 값의 평균 또는 가운데 값
  function medTex(a) {
    var n = a.length, h = Math.floor(n / 2);
    return n % 2 ? String(a[h]) : '\\frac{' + a[h - 1] + '+' + a[h] + '}{2}=' + fmt(med(a));
  }
