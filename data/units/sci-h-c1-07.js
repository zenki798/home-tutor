function doped(sym, kind, alt) {
  var P = [40, 100, 160], out = [];
  function e(x, y, empty) {
    out.push(empty
      ? '<circle cx="' + x + '" cy="' + y + '" r="4" fill="none" stroke="var(--fig-2)" stroke-width="1.5" stroke-dasharray="2 2"/>'
      : '<circle cx="' + x + '" cy="' + y + '" r="3.5" fill="var(--fig-1)"/>');
  }
  P.forEach(function (y, j) {
    P.forEach(function (x, i) {
      // 오른쪽·아래 결합, 가장자리는 바깥으로 짧은 결합
      [[1, 0], [0, 1], [-1, 0], [0, -1]].forEach(function (d) {
        var ni = i + d[0], nj = j + d[1];
        var inside = ni >= 0 && ni < 3 && nj >= 0 && nj < 3;
        if (inside && (d[0] < 0 || d[1] < 0)) return;
        // 가장자리 결합은 40: 결합 전자(중점, 원자 중심에서 20)가 원자 원(반지름 15)에 가리지 않게
        var len = inside ? 60 : 40;
        var x2 = x + d[0] * len, y2 = y + d[1] * len;
        out.push('<line x1="' + x + '" y1="' + y + '" x2="' + x2 + '" y2="' + y2 + '" stroke="currentColor" stroke-opacity="0.35"/>');
        var mx = x + d[0] * len / 2, my = y + d[1] * len / 2;
        var ox = d[1] !== 0 ? 5 : 0, oy = d[0] !== 0 ? 5 : 0;
        var isHole = kind === 'p' && i === 1 && j === 1 && d[0] === 1 && d[1] === 0;
        e(mx - ox, my - oy);
        e(mx + ox, my + oy, isHole);
      });
    });
  });
  P.forEach(function (y, j) {
    P.forEach(function (x, i) {
      var c = i === 1 && j === 1;
      out.push('<circle cx="' + x + '" cy="' + y + '" r="15" fill="var(--fig-' + (c ? 2 : 3) + ')" fill-opacity="0.35" stroke="currentColor"/>');
      out.push('<text x="' + x + '" y="' + (y + 4) + '" font-size="11" text-anchor="middle" fill="currentColor">' + (c ? sym : 'Si') + '</text>');
    });
  });
  if (kind === 'n') {
    e(121, 79);
    // 위쪽 결합(x=100)·오른쪽 위 규소의 아래 결합(x=160) 전자와 겹치지 않게 칸 한가운데에 쓴다
    out.push('<text x="130" y="64" font-size="9" text-anchor="middle" fill="currentColor">남는 전자</text>');
  } else {
    out.push('<text x="122" y="122" font-size="10" fill="currentColor">양공</text>');
  }
  return { type: 'svg', alt: alt, svg: '<svg viewBox="0 0 200 200" xmlns="http://www.w3.org/2000/svg">' + out.join('') + '</svg>' };
}

