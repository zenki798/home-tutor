  // bank: [[사례, 정답 이름, 해설]], why: 이름 → 그 이름을 잘못 고른 학생에게 보일 말, concept: 번호 또는 이름 → 번호
  function caseProblem(R, lead, bank, names, why, concept, n) {
    var c = R.pick(bank);
    var k = n || names.length;
    var wrongs = R.shuffle(names.filter(function (x) { return x !== c[1]; }));
    var ch = R.choices(c[1], wrongs, k);
    return {
      type: 'choice',
      q: lead + '\n\n' + c[0],
      choices: ch.choices,
      answer: ch.answer,
      why: ch.choices.map(function (x) { return x === c[1] ? '' : why[x]; }),
      explain: c[2],
      concept: typeof concept === 'number' ? concept : concept[c[1]],
    };
  }

