  function ORDN(n) {
    var ones = ['', '한', '두', '셋', '넷', '다섯', '여섯', '일곱', '여덟', '아홉'];
    if (n <= 8) return ORD[n - 1];
    if (n === 9) return '아홉째';
    if (n === 10) return '열째';
    if (n === 20) return '스무째';
    return '열' + ones[n - 10] + '째';
  }
