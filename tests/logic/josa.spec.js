const { test, expect } = require('@playwright/test');
const path = require('path');
const TutorMath = require(path.join(__dirname, '..', '..', 'js', 'mathlib.js'));

/*
 * 조사 고르기 — 생성기 문장이 수에 따라 "9/8은"·"6/5가" 같은 틀린 조사를 내지 않게.
 * 기준은 읽는 소리의 마지막 받침이다: 분수는 분자("8분의 구"), 대분수도 분자, 0으로 끝나는 수는 십·백·천·만.
 */
const BS = String.fromCharCode(92);
const frac = (a, b) => '$' + BS + 'frac{' + a + '}{' + b + '}$';

const CASES = [
  // 수: 일의 자리
  [1, '을/를', '을'], [2, '을/를', '를'], [3, '을/를', '을'], [4, '을/를', '를'], [5, '을/를', '를'],
  [6, '을/를', '을'], [7, '을/를', '을'], [8, '을/를', '을'], [9, '을/를', '를'], [0, '이/가', '이'],
  // 0으로 끝나는 수: 십(ㅂ)·백(ㄱ)·천(ㄴ)·만(ㄴ)
  [10, '은/는', '은'], [20, '이에요/예요', '이에요'], [100, '이/가', '이'], [1000, '은/는', '은'], [50000, '을/를', '을'],
  ['1,000', '을/를', '을'], [-3, '이/가', '이'],
  // 소수: 마지막 숫자를 읽는다
  [2.5, '이에요/예요', '예요'], [0.1, '으로/로', '로'], [1.6, '이/가', '이'],
  // ㄹ 받침은 '로'
  [7, '으로/로', '로'], [8, '으로/로', '로'], [1, '으로/로', '로'], [3, '으로/로', '으로'], [9, '으로/로', '로'],
  // 분수·대분수: 분자
  ['3/4', '을/를', '을'], ['1 2/5', '이에요/예요', '예요'],
  [frac(9, 8), '은/는', '는'], [frac(6, 5), '이/가', '이'], [frac(7, 10), '이에요/예요', '이에요'],
  ['$1' + BS + 'frac{2}{5}$', '이에요/예요', '예요'], ['$2' + BS + 'frac{3}{7}$', '을/를', '을'],
  // 한글 낱말
  ['민수', '이/가', '가'], ['지훈', '이/가', '이'], ['서울', '으로/로', '로'], ['부산', '으로/로', '으로'], ['사과', '과/와', '와'], ['귤', '과/와', '과'],
  // 단위·영어
  ['cm', '을/를', '를'], ['kg', '을/를', '을'], ['L', '이/가', '가'], ['apple', '은/는', '는'], ['school', '은/는', '은'],
  // 식: 마지막에 읽는 것
  ['$x+3$', '이/가', '이'], ['$2x$', '을/를', '를'],
];

test('조사: 읽는 소리의 받침으로 고른다', () => {
  for (const [x, pair, want] of CASES) {
    expect(TutorMath.josa(x, pair), JSON.stringify(x) + ' ' + pair).toBe(want);
  }
});

test('조사: Frac 은 분자로 읽는다', () => {
  expect(TutorMath.josa(TutorMath.F(9, 8), '은/는')).toBe('는');
  expect(TutorMath.josa(TutorMath.F(6, 5), '이/가')).toBe('이');
});

test('조사: 문제 생성 도구 R 에도 있다', () => {
  const R = TutorMath.toolkit(1);
  expect(R.josa(6, '이/가')).toBe('이');
  expect(R.josa('지아', '은/는')).toBe('는');
});

test('조사: 잘못된 쌍은 throw', () => {
  expect(() => TutorMath.josa(3, '을를')).toThrow();
});
